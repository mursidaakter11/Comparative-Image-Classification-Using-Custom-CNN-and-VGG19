"""Build VGG19 Classification Model"""

def build_vgg19():

    inputs = layers.Input(
        shape=(224, 224, 3)
    )

    features = vgg_base(inputs, training=False)

    x = layers.GlobalAveragePooling2D()(features)

    x = layers.Dense(
        128,
        activation="relu"
    )(x)

    x = layers.Dropout(0.30)(x)

    outputs = layers.Dense(
        1,
        activation="sigmoid"
    )(x)

    model = models.Model(
        inputs=inputs,
        outputs=outputs
    )

    return model


